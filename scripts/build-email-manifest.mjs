#!/usr/bin/env node
/**
 * Hand the PHP mailer what it needs to fill the guide email, from the same
 * records that build the guide pages.
 *
 *   node scripts/build-email-manifest.mjs        (runs from `npm run build`)
 *
 * Writes public/api/guides.php: slug => { title, file, category, pages,
 * summary, chapters }.
 *
 * WHY GENERATED AND NOT HAND-KEPT. contact.php already carried a hand-written
 * GUIDE_SLUGS allowlist that validate-content.mjs had to police against the URL
 * inventory, because two hand-kept lists disagree the first time somebody edits
 * one. The email needs four more fields per guide on top of the slug, which
 * would have been four more chances for the same drift. Now the content
 * collection is the only place a guide is described, and the allowlist falls
 * out of it: a slug that is not in this file is not a guide, and contact.php
 * refuses it before it touches the filesystem.
 *
 * `pages` comes from the "ONE PAGE" pill, which every guide carries today. It
 * is read rather than assumed: a guide that stops being one page loses the pill
 * and the email stops claiming it. No pill, no Pages row.
 *
 * `chapters` are the guide's own section headings. They are the same three on
 * fourteen of the fifteen — purpose, method, pitfalls — which is a fact about
 * how the guides are written, not a placeholder. business-model-canvas has two,
 * and its email prints two rows.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'src/content/resources')
const OUT = join(ROOT, 'public/api/guides.php')

/** Minimal frontmatter reads. The collection schema has already validated
 *  these files by the time anything ships; this only needs the five fields. */
const one = (s, key) => (s.match(new RegExp(`^${key}:\\s*"([^"]*)"`, 'm')) ?? [])[1]
const list = (s, key) => {
  const raw = (s.match(new RegExp(`^${key}:\\s*\\[([^\\]]*)\\]`, 'm')) ?? [])[1]
  return raw ? [...raw.matchAll(/"([^"]*)"/g)].map((m) => m[1]) : []
}

const guides = {}
for (const f of readdirSync(SRC).sort()) {
  if (!f.endsWith('.md')) continue
  const s = readFileSync(join(SRC, f), 'utf8')
  const file = one(s, 'file')
  if (!file) continue // not a gated PDF; it is a read-on-the-page resource

  const pills = list(s, 'pills')
  const headings = [...s.matchAll(/^ {4}heading:\s*"([^"]+)"/gm)].map((m) => m[1])
  guides[f.replace(/\.md$/, '')] = {
    title: one(s, 'title'),
    file,
    // pills[0] is always "PDF" and pills[1] the page count; the last one is the
    // shelf it sits on, which is what the email's LIBRARY line names.
    category: pills.at(-1) ?? '',
    pages: pills.includes('ONE PAGE') ? '1' : '',
    summary: one(s, 'summary') ?? '',
    chapters: headings.slice(0, 3),
  }
}

const q = (v) => "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"
const rows = Object.entries(guides).map(([slug, g]) => {
  const ch = g.chapters.map(q).join(', ')
  return (
    `    ${q(slug)} => [\n` +
    `        'title' => ${q(g.title)},\n` +
    `        'file' => ${q(g.file)},\n` +
    `        'category' => ${q(g.category)},\n` +
    `        'pages' => ${q(g.pages)},\n` +
    `        'summary' => ${q(g.summary)},\n` +
    `        'chapters' => [${ch}],\n` +
    `    ],`
  )
})

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(
  OUT,
  `<?php
/**
 * GENERATED by scripts/build-email-manifest.mjs. Do not edit.
 *
 * Every gated guide, described once, from src/content/resources/*.md. This is
 * also contact.php's allowlist: a slug absent from these keys is refused before
 * anything touches the filesystem, so no string from a request ever reaches a
 * filename.
 */
declare(strict_types=1);

return [
${rows.join('\n')}
];
`,
)

console.log(`build-email-manifest: ${rows.length} guide(s) -> public/api/guides.php`)
for (const [slug, g] of Object.entries(guides)) {
  console.log(`  ${slug.padEnd(34)} ${g.category.padEnd(18)} ${g.chapters.length} chapter(s)`)
}
